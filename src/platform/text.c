void text_draw(SDL_Renderer *r, int x, int y, int px, const char *s)
{
    SDL_Rect rects[256];
    int n = 0;
    for (int cx = x; *s; s++, cx += TEXT_CELL_W * px) {
        unsigned char c = (unsigned char)*s;
        if (c < 32 || c > 126)
            c = '?';
        int drop = c == 'g' || c == 'p' || c == 'q' || c == 'y' ? 2 : 0;
        for (int row = 0; row < 7; row++)
            for (int col = 0; col < 5; col++)
                if (glyphs[c - 32][row] & (0x10 >> col)) {
                    rects[n++] = (SDL_Rect){ cx + col * px, y + (row + drop) * px, px, px };
                    if (n == (int)(sizeof rects / sizeof rects[0])) {
                        SDL_RenderFillRects(r, rects, n);
                        n = 0;
                    }
                }
    }
    if (n)
        SDL_RenderFillRects(r, rects, n);
}

int text_wrap(const char *in, int cols, char *out, size_t out_len)
{
    size_t used = 0;
    int lines = 0;
    if (out_len)
        out[0] = 0;
    for (const char *line = in; *line; ) {
        size_t len = strcspn(line, "\n");
        /* indent continuation lines of "- " list items */
        int indent = len >= 2 && line[0] == '-' && line[1] == ' ' ? 2 : 0;
        const char *p = line, *end = line + len;
        int first = 1;
        do {
            int width = cols - (first ? 0 : indent);
            const char *stop = p + width < end ? p + width : end;
            if (stop < end) {
                const char *space = stop;
                while (space > p && *space != ' ')
                    space--;
                if (space > p)
                    stop = space;
            }
            int pad = first ? 0 : indent;
            size_t need = (size_t)pad + (size_t)(stop - p) + 1;
            if (used + need + 1 > out_len)
                return lines;
            memset(out + used, ' ', (size_t)pad);
            memcpy(out + used + pad, p, (size_t)(stop - p));
            used += need;
            out[used - 1] = '\n';
            out[used] = 0;
            lines++;
            p = stop;
            while (p < end && *p == ' ')
                p++;
            first = 0;
        } while (p < end);
        line = *end ? end + 1 : end;
    }
    return lines;
}
